import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const context = vm.createContext({ console });
for (const file of ["checkpoint-core.js", "runner-core.js", "output-location-core.js", "xlsx-run-plan-core.js"]) vm.runInContext(fs.readFileSync(new URL(`../${file}`, import.meta.url), "utf8"), context, { filename: file });
const { DacRunnerCore: runner, DacOutputLocation: output, DacXlsxRunPlan: plan } = context;
const config = { timeout_sec: "300", max_retries: "2", delay_min_sec: "3", delay_max_sec: "5", safety_cooldown_sec: "2", max_input_images: "5", continue_on_error: "true", rerun_done: "false", output_destination_mode: "downloads", output_downloads_subfolder: "Duc Auto ChatGPT/Pilot04", image_filename_pattern: "{job_id}-{attempt}", collision_policy: "uniquify", save_images: "true", save_result_xlsx: "true", save_audit_jsonl: "true", result_filename_pattern: "pilot-04__results__v{version}.xlsx", audit_filename: "pilot-04-audit.jsonl" };
const jobs = [{ id: "P04-A", prompt: "a" }, { id: "P04-B", prompt: "b" }];
const imported = plan.validate(config, jobs, runner, output);
assert.equal(imported.findings.filter((item) => item.severity === "BLOCKER").length, 0);
assert.equal(imported.effective.runtime.timeout_sec, 300);
assert.equal(imported.effective.output.downloadsSubfolder, "Duc Auto ChatGPT/Pilot04");
assert.equal(imported.effective.output.imagePattern, "{job_id}-{attempt}");
assert.equal(imported.effective.output.saveAuditJsonl, true);
const importedOutput = output.fromWorkbook(config, "pilot-04.xlsx");
assert.equal(importedOutput.image.folder, "Duc Auto ChatGPT/Pilot04");
assert.equal(importedOutput.resultFilenamePattern, "pilot-04__results__v{version}.xlsx");
assert.equal(importedOutput.auditFilename, "pilot-04-audit.jsonl");
const invalid = plan.validate({ ...config, timeout_sec: "2", output_destination_mode: "folder", collision_policy: "surprise", output_downloads_subfolder: "C:\\temp", save_images: "maybe" }, [{ id: "../bad", prompt: "x" }], runner, output);
assert.equal(invalid.findings.some((item) => item.code === "INVALID_RUN_CONFIG"), true);
assert.equal(invalid.findings.some((item) => item.code === "INVALID_OUTPUT_DESTINATION_MODE"), true);
assert.equal(invalid.findings.some((item) => item.code === "INVALID_COLLISION_POLICY"), true);
assert.equal(invalid.findings.some((item) => item.code === "INVALID_JOB_ID"), true);
const unknown = plan.validate({ ...config, made_up_key: "x" }, jobs, runner, output);
assert.equal(unknown.findings.some((item) => item.code === "UNKNOWN_CONFIG_KEY" && item.severity === "WARNING"), true);
const profile = plan.validate({ ...config, output_destination_mode: "profile", output_profile_id: "pilot-04" }, jobs, runner, output);
assert.equal(profile.findings.filter((item) => item.severity === "BLOCKER").length, 0);
console.log("xlsx run plan core smoke: PASS");
