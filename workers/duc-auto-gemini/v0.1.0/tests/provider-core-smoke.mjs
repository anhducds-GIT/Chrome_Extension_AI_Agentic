import { assert, load, pass } from "./test-helpers.mjs";
const Core = await load(new URL("../provider-core.js", import.meta.url), "DagProviderCore");
assert.equal(Core.surface("https://gemini.google.com/images"), "IMAGES");
assert.equal(Core.surface("https://gemini.google.com/app/abc"), "CONVERSATION");
assert.equal(Core.surface("https://gemini.google.com/library"), "WRONG");
assert.equal(Core.surface("https://evil.example/images"), "WRONG");
assert.equal(Core.securityBlocker("Verify you are human because unusual activity was detected"), "SECURITY_BLOCKER");
assert.equal(Core.quotaOrPolicyBlocker("You have reached your image generation limit. Try again later."), "QUOTA_LIMIT");
assert.equal(Core.quotaOrPolicyBlocker("I cannot generate this image because of policy."), "POLICY_BLOCK");
const boundary = Core.boundary([{ src:"old",role:"model" }], { url:"https://gemini.google.com/images", model_count:1, captured_at:"2026-08-24T00:00:00Z" });
assert.equal(Core.outputDecision(boundary, [{src:"old",role:"model",visible:true,usable:true}], {}).reason, "NO_FRESH_OUTPUT");
assert.equal(Core.outputDecision(boundary, [{src:"new",role:"unknown",visible:true,usable:true}], {}).reason, "FRESH_OUTPUT_NOT_ATTRIBUTABLE");
assert.equal(Core.outputDecision(boundary, [{src:"new-1",role:"model",visible:true,usable:true},{src:"new-2",role:"model",visible:true,usable:true}], {}).reason, "AMBIGUOUS_MULTIPLE_OUTPUTS");
assert.equal(Core.outputDecision(boundary, [{src:"new",role:"model",visible:true,usable:true}], {generating:true}).reason, "GENERATION_ACTIVE");
assert.equal(Core.outputDecision(boundary, [{src:"new",role:"model",visible:true,usable:true}], {}).ok, true);
let attempt = Core.createAttempt({runId:"run",jobId:"job",attemptId:"a1",boundary});
attempt = Core.transition(attempt,"SUBMITTED");
assert.equal(Core.retryDecision(attempt,"SEND_NOT_READY",0,2).allowed,false,"submitted attempts never retry");
assert.throws(()=>Core.transition(attempt,"SUCCESS"),/INVALID_TRANSITION/);
pass("provider core: surface, blockers, attribution and exact-once");
