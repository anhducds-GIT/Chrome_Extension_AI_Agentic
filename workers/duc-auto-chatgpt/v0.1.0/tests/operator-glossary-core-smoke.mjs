import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL("../operator-glossary-core.js", import.meta.url), "utf8"), context);
const entries = context.DacOperatorGlossary.GLOSSARY;
for (const term of ["Giới hạn thời gian", "Số lần thử lại", "Thời gian nghỉ an toàn", "Khoảng nghỉ giữa các tác vụ", "Đang chờ ChatGPT sẵn sàng", "Đang đối soát", "Đã xác minh lưu tệp", "Chỉ gửi một lần", "Dừng bắt buộc vì bảo mật"]) assert.ok(entries.some((entry) => entry.term === term), `${term} is defined`);
assert.deepEqual([...new Set(entries.map((entry) => entry.section))], ["THIẾT LẬP", "CHẠY", "ĐẦU RA", "TRẠNG THÁI / LỖI", "THỜI GIAN"]);
assert.match(entries.find((entry) => entry.term === "Giới hạn thời gian").detail, /không phải là một bộ đếm thời gian chung/i);
assert.match(entries.find((entry) => entry.term === "Đang chờ ChatGPT sẵn sàng").detail, /không tự nó cho phép gửi prompt/i);
console.log("operator glossary core smoke: PASS");
